def env_ladder():
    src = open("fm_tables.h").read()
    body = re.search(r"ENV_MS\[ENV_STEPS\]\s*=\s*\{(.*?)\};", src, re.S).group(1)
    return [int(x) for x in re.findall(r"\d+", body)]

LADDER = env_ladder()

def ladder_index(seconds):
    """Nearest step of the envelope ladder, in log time. Index 0 is INSTANT."""
    ms = seconds * 1000.0
    if ms < 1.0: return 0
    best, bi = 1e9, 1
    for i, v in enumerate(LADDER[1:], 1):
        d = abs(math.log(ms) - math.log(v))
        if d < best: best, bi = d, i
    return bi

def t96(rate):
    """Seconds for a full 96 dB decay at YM EG rate 0..63: roughly doubling every 4 rates,
    ~6.7 ms at rate 60. An approximation of the YM2151/YM2414 envelope, good to a ladder step."""
    if rate >= 62: return 0.004
    if rate <= 0: return 1e9
    return 0.0067 * 2.0 ** ((60 - rate) / 4.0)

def env(ar, d1r, d2r, rr, d1l):
    a = 31 if ar == 0 else ladder_index(0.0 if ar >= 31 else t96(2 * ar) / 5.0)
    drop1 = 93 if d1l == 0 else (15 - d1l) * 3          # dB below full where decay 1 ends
    sus = int(round(15 * 10 ** (-drop1 / 20.0)))
    tail = t96(2 * d2r) * 0.625 if d2r else 1e9          # decay 2's time over 60 dB
    # A D2R decay is honoured unless it is so slow it is effectively a sustain (over ~15 s). The
    # first version only honoured tails under 4 s, so plucked voices whose D2R ran 4-8 s - Koto,
    # NylonGuit - held at full brightness for as long as the gate did, and sounded harsh.
    if d2r and tail < 15.0:
        # The note keeps dying while held: one decay to silence covering both stages.
        if drop1 >= 60:
            t = t96(2 * d1r) * 60 / 96.0
        else:
            t = t96(2 * d1r) * drop1 / 96.0 + t96(2 * d2r) * (60 - drop1) / 96.0
        dec, sus = ladder_index(t), 0
    else:
        dec = ladder_index(t96(2 * d1r) * 0.625)
    rel = ladder_index(t96(4 * rr + 2) * 0.625)
    return a, dec, sus, max(1, rel)

def ratio_to_ours(r):
    """coarse x (1 + fine/100), coarse 0 = 0.5."""
    if r < 1.0:
        c, base = 0, 0.5
    else:
        c, base = min(31, int(r)), float(min(31, int(r)))
    f = int(round((r / base - 1.0) * 100))
    return c, max(0, min(99, f))

def convert(hexs):
    d = bytes.fromhex(hexs)
    ops = {}
    for k in range(4):
        b, e = 10 * k, 73 + 2 * k
        crs, fin = d[b + 8] & 63, d[e + 1] & 15
        lo, hi = FREQ[crs], FREQ_MAX[crs]
        r = min(hi, lo + (hi - lo) / 7 * fin) if lo < 1.0 else lo + (hi - lo) / 15 * fin
        c, f = ratio_to_ours(r)
        # DET is a small FIXED frequency offset on the YM chips (DT1), the same few Hz whatever
        # the operator's ratio. This engine detunes in cents of the operator's own frequency, so
        # the cents are divided by the ratio to keep the offset in Hz constant: ~2 cents of the
        # fundamental per step. (Converting it as plain cents put DX7 EP's 15x tine 23 Hz out.)
        det = int(round((min(d[b + 9] & 7, 6) - 3) * 2 / r))
        a, dec, sus, rel = env(d[b] & 31, d[b + 1] & 31, d[b + 2] & 31, d[b + 3] & 15, d[b + 4] & 15)
        ops[OP_FOR_SLOT[k]] = (c, f, det, min(d[b + 7] & 127, 99), a, dec, sus, rel, r)
    alg, fb = d[40] & 7, (d[40] >> 3) & 7
    trps = min(d[46] & 63, 48) - 24
    trps = max(-24, min(24, trps))
    return alg, fb, trps, [ops[1], ops[2], ops[3], ops[4]]

def main():
    out = []
    out.append("// presets4.h - GENERATED by gen_dx_presets.py from Bryan Sutula's TX81Z/DX11 Voice Archive.")
    out.append("// Do not edit by hand: edit the generator (its docstring says what converts and what does not).")
    out.append("#pragma once\n")
    out.append("// %d voices; presets.c asserts this matches PRESET4_COUNT in presets.h." % len(RAW))
    out.append("static const Preset4 PRESET4[] = {")
    for name, source, hexs in RAW:
        alg, fb, trps, ops = convert(hexs)
        cname = " ".join(name.split())[:10]
        out.append("    // %s - %s. Ratios: %s" % (cname, source, ", ".join("%.2f" % o[8] for o in ops)))
        out.append('    { "%s", %d, %d, %d, 0, 0, {' % (cname, alg, fb, trps))
        for i, o in enumerate(ops):
            out.append("        { %2d, %2d, %3d, %2d, { %2d, %2d, %2d, %2d } }%s" %
                       (o[0], o[1], o[2], o[3], o[4], o[5], o[6], o[7], "," if i < 3 else ""))
        out.append("    } },")
    out.append("};")
    open("presets4.h", "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote presets4.h (%d voices)" % len(RAW))

if __name__ == "__main__":
    main()
